package skillgen

import (
	"errors"
	"os"
	"path/filepath"
	"regexp"
	"strings"

	"github.com/inhere/apic/internal/model"
)

var namePattern = regexp.MustCompile(`^[a-z0-9][a-z0-9-]{0,63}$`)

// hasMarker reports whether the first line after the frontmatter is Marker.
func hasMarker(data []byte) bool {
	lines := strings.Split(strings.ReplaceAll(string(data), "\r\n", "\n"), "\n")
	if len(lines) < 3 || lines[0] != "---" {
		return false
	}
	for i := 1; i < len(lines)-1; i++ {
		if lines[i] == "---" {
			return lines[i+1] == Marker
		}
	}
	return false
}

// Write stores data as <parent>/<name>/SKILL.md atomically. It never follows
// symlinks at the skill directory or file, and only replaces an existing file
// that carries Marker unless force is set.
func Write(parent, name string, data []byte, force bool) (string, error) {
	if !namePattern.MatchString(name) {
		return "", model.Errorf(model.ExitUsage, "invalid skill name %q (expected ^[a-z0-9][a-z0-9-]{0,63}$)", name)
	}
	dir := filepath.Join(parent, name)
	path := filepath.Join(dir, "SKILL.md")
	if fi, err := os.Lstat(dir); err == nil {
		if fi.Mode()&os.ModeSymlink != 0 {
			return "", model.Errorf(model.ExitLocal, "refusing to write through symlink %s", dir)
		}
		if !fi.IsDir() {
			return "", model.Errorf(model.ExitLocal, "%s is not a directory", dir)
		}
	} else if !errors.Is(err, os.ErrNotExist) {
		return "", model.Errorf(model.ExitLocal, "%s: %v", dir, err)
	}
	if fi, err := os.Lstat(path); err == nil {
		if fi.Mode()&os.ModeSymlink != 0 {
			return "", model.Errorf(model.ExitLocal, "refusing to write through symlink %s", path)
		}
		if !fi.Mode().IsRegular() {
			return "", model.Errorf(model.ExitLocal, "%s is not a regular file", path)
		}
		old, err := os.ReadFile(path)
		if err != nil {
			return "", model.Errorf(model.ExitLocal, "%s: %v", path, err)
		}
		if !force && !hasMarker(old) {
			return "", model.Errorf(model.ExitLocal, "%s exists and was not generated by apic skill (use --force to overwrite)", path)
		}
	} else if !errors.Is(err, os.ErrNotExist) {
		return "", model.Errorf(model.ExitLocal, "%s: %v", path, err)
	}
	if err := os.MkdirAll(dir, 0755); err != nil {
		return "", model.Errorf(model.ExitLocal, "%s: %v", dir, err)
	}
	tmp, err := os.CreateTemp(dir, ".SKILL.md.*")
	if err != nil {
		return "", model.Errorf(model.ExitLocal, "%s: %v", dir, err)
	}
	tmpName := tmp.Name()
	fail := func(err error) (string, error) {
		_ = os.Remove(tmpName)
		return "", model.Errorf(model.ExitLocal, "%s: %v", path, err)
	}
	if _, err := tmp.Write(data); err != nil {
		_ = tmp.Close()
		return fail(err)
	}
	if err := tmp.Close(); err != nil {
		return fail(err)
	}
	if err := os.Chmod(tmpName, 0644); err != nil {
		return fail(err)
	}
	if err := os.Rename(tmpName, path); err != nil {
		return fail(err)
	}
	return path, nil
}
