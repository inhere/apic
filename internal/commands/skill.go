package commands

import (
	"os"
	"path/filepath"

	"github.com/gookit/gcli/v3"
	"github.com/inhere/apic/internal/config"
	"github.com/inhere/apic/internal/model"
	"github.com/inhere/apic/internal/skillgen"
	"github.com/inhere/apic/internal/wiring"
)

type skillOptions struct {
	out, name string
	maxOps    int
	force     bool
}

func skillCommand(info BuildInfo) *gcli.Command {
	opt := &skillOptions{}
	return &gcli.Command{Name: "skill", Desc: "Generate an agent skill (SKILL.md) for a site, or for apic itself when no site is given", Config: func(c *gcli.Command) {
		c.AddArg("site", "Site name; omit it to describe apic itself", false)
		c.StrOpt(&opt.out, "out", "", "", "Parent directory (default <config dir>/skills)")
		c.StrOpt(&opt.name, "name", "", "", "Skill name (default apic-<site>, or apic without a site)")
		c.IntOpt(&opt.maxOps, "max-ops", "", 60, "List operations individually up to this count")
		c.BoolOpt(&opt.force, "force", "", false, "Overwrite a file not generated by apic skill")
	}, Func: func(c *gcli.Command, _ []string) error {
		return generateSkill(info, c.Arg("site").String(), opt)
	}}
}

func generateSkill(info BuildInfo, name string, opt *skillOptions) error {
	if name == "" {
		return generateSelfSkill(info, opt)
	}
	d, err := wiring.Load()
	if err != nil {
		return err
	}
	site, err := siteLookup(d, name)
	if err != nil {
		return err
	}
	idx, _, warnings, err := loadSiteIndex(d, name, site, "")
	if err != nil {
		return err
	}
	if err := printWarnings(d, warnings); err != nil {
		return err
	}
	skill := opt.name
	if skill == "" {
		skill = "apic-" + name
	}
	parent := opt.out
	if parent == "" {
		parent = filepath.Join(d.Dir, "skills")
	}
	data, err := skillgen.Render(skillgen.Input{Site: name, Index: idx, Cfg: site, Name: skill, MaxOps: opt.maxOps})
	if err != nil {
		return err
	}
	path, err := skillgen.Write(parent, skill, data, opt.force)
	if err != nil {
		return err
	}
	if err := writeString(os.Stderr, "install with skillc: skillc install -S "+parent+" "+skill+"\n"+
		"review the file before sharing: it lists internal API paths\n"); err != nil {
		return err
	}
	return writeString(os.Stdout, path+"\n")
}

// generateSelfSkill writes the skill for apic itself. It never loads the site
// configuration, so a missing or broken config directory still works; --max-ops
// does not apply to a static template.
func generateSelfSkill(info BuildInfo, opt *skillOptions) error {
	skill := opt.name
	if skill == "" {
		skill = "apic"
	}
	parent := opt.out
	if parent == "" {
		dir, err := config.Dir()
		if err != nil {
			return model.Errorf(model.ExitUsage, "--out is required: %v", err)
		}
		parent = filepath.Join(dir, "skills")
	}
	data, err := skillgen.RenderSelf(skill, info.Version)
	if err != nil {
		return err
	}
	path, err := skillgen.Write(parent, skill, data, opt.force)
	if err != nil {
		return err
	}
	if err := writeString(os.Stderr, "install with skillc: skillc install -S "+parent+" "+skill+"\n"); err != nil {
		return err
	}
	return writeString(os.Stdout, path+"\n")
}
