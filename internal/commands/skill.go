package commands

import (
	"os"
	"path/filepath"

	"github.com/gookit/gcli/v3"
	"github.com/inhere/apic/internal/skillgen"
	"github.com/inhere/apic/internal/wiring"
)

type skillOptions struct {
	out, name string
	maxOps    int
	force     bool
}

func skillCommand() *gcli.Command {
	opt := &skillOptions{}
	return &gcli.Command{Name: "skill", Desc: "Generate an agent skill (SKILL.md) for a site", Config: func(c *gcli.Command) {
		c.AddArg("site", "Site name", true)
		c.StrOpt(&opt.out, "out", "", "", "Parent directory (default <config dir>/skills)")
		c.StrOpt(&opt.name, "name", "", "", "Skill name (default apic-<site>)")
		c.IntOpt(&opt.maxOps, "max-ops", "", 60, "List operations individually up to this count")
		c.BoolOpt(&opt.force, "force", "", false, "Overwrite a file not generated by apic skill")
	}, Func: func(c *gcli.Command, _ []string) error {
		return generateSkill(c.Arg("site").String(), opt)
	}}
}

func generateSkill(name string, opt *skillOptions) error {
	d, err := wiring.Load()
	if err != nil {
		return err
	}
	site, err := siteLookup(d, name)
	if err != nil {
		return err
	}
	idx, _, warnings, err := loadSiteIndex(d, name, site, "")
	if err != nil {
		return err
	}
	if err := printWarnings(d, warnings); err != nil {
		return err
	}
	skill := opt.name
	if skill == "" {
		skill = "apic-" + name
	}
	parent := opt.out
	if parent == "" {
		parent = filepath.Join(d.Dir, "skills")
	}
	data, err := skillgen.Render(skillgen.Input{Site: name, Index: idx, Cfg: site, Name: skill, MaxOps: opt.maxOps})
	if err != nil {
		return err
	}
	path, err := skillgen.Write(parent, skill, data, opt.force)
	if err != nil {
		return err
	}
	if err := writeString(os.Stderr, "install with skillc: skillc install -S "+parent+" "+skill+"\n"+
		"review the file before sharing: it lists internal API paths\n"); err != nil {
		return err
	}
	return writeString(os.Stdout, path+"\n")
}
